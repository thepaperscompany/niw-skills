#!/usr/bin/env bash
# Copy declared knowledge/ files into each skill's references/ directory and
# record a checksum manifest.
#
# knowledge/ is the single source of truth. Files under skills/*/references/
# are generated artifacts: edit knowledge/ and re-run this, never the copies.
# They are committed anyway so a standalone .skill works on claude.ai, where
# there is no plugin root to resolve a shared path against.
#
# Usage:
#   build/vendor.sh           write the vendored copies and the manifest
#   build/vendor.sh --check   verify copies match knowledge/; exit 1 on drift

set -uo pipefail
cd "$(dirname "$0")/.." || exit 2

CHECK=0
[ "${1:-}" = "--check" ] && CHECK=1

sha() { shasum -a 256 "$1" | cut -d' ' -f1; }

drift=0
copied=0
manifest_tmp="$(mktemp)"
echo "# Generated by build/vendor.sh. Do not edit." > "$manifest_tmp"
echo "# sha256  knowledge-file  ->  vendored-path" >> "$manifest_tmp"

while read -r skill file; do
  case "$skill" in ''|\#*) continue ;; esac
  src="knowledge/$file"
  dstdir="thepapers-niw/skills/$skill/references"
  dst="$dstdir/$file"

  if [ ! -f "$src" ]; then
    echo "ERROR: $src declared in build/vendor.map but missing"
    exit 2
  fi

  if [ "$CHECK" -eq 1 ]; then
    if [ ! -f "$dst" ]; then
      echo "DRIFT  missing vendored copy: $dst"
      drift=1
    elif [ "$(sha "$src")" != "$(sha "$dst")" ]; then
      echo "DRIFT  $dst differs from $src"
      drift=1
    fi
  else
    mkdir -p "$dstdir"
    cp "$src" "$dst"
    copied=$((copied + 1))
  fi

  printf '%s  %s  ->  %s\n' "$(sha "$src")" "$src" "$dst" >> "$manifest_tmp"
done < build/vendor.map

if [ "$CHECK" -eq 1 ]; then
  if [ "$drift" -ne 0 ]; then
    echo
    echo "FAILED: vendored references are out of date. Run build/vendor.sh."
    exit 1
  fi
  echo "OK: vendored references match knowledge/."
  exit 0
fi

mv "$manifest_tmp" knowledge/MANIFEST.txt
echo "OK: vendored $copied files; wrote knowledge/MANIFEST.txt"
